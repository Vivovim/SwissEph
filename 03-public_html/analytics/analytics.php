function pagination(string $key, int $current, int $total, array $filters, string $anchor): void
{
    if ($total <= 1) {
        return;
    }
    echo '<nav class="pagination" aria-label="' . escape($anchor) . ' pagination">';
    if ($current > 1) {
        $href = '?' . http_build_query(array_replace($filters, [$key => $current - 1]), '', '&', PHP_QUERY_RFC3986);
        echo '<a href="' . escape($href . '#' . $anchor) . '">← Previous</a>';
    }
    echo '<span>Page ' . number_format($current) . ' of ' . number_format($total) . '</span>';
    if ($current < $total) {
        $href = '?' . http_build_query(array_replace($filters, [$key => $current + 1]), '', '&', PHP_QUERY_RFC3986);
        echo '<a href="' . escape($href . '#' . $anchor) . '">Next →</a>';
    }
    echo '</nav>';
}
