function basicCredentials(): array
{
    if (isset($_SERVER['PHP_AUTH_USER'], $_SERVER['PHP_AUTH_PW'])
        && is_string($_SERVER['PHP_AUTH_USER']) && is_string($_SERVER['PHP_AUTH_PW'])) {
        return [$_SERVER['PHP_AUTH_USER'], $_SERVER['PHP_AUTH_PW']];
    }

    // Some CGI/FastCGI hosts forward the header without populating PHP_AUTH_*.
    // Read only request metadata, never query parameters or cookies.
    $authorization = $_SERVER['HTTP_AUTHORIZATION'] ?? $_SERVER['REDIRECT_HTTP_AUTHORIZATION'] ?? '';
    if (!is_string($authorization) || strlen($authorization) > 8192
        || !preg_match('/\ABasic +([A-Za-z0-9+\/=]+)\z/i', $authorization, $matches)) {
        return ['', ''];
    }
    $decoded = base64_decode($matches[1], true);
    if ($decoded === false || !str_contains($decoded, ':')
        || preg_match('/[\x00-\x1F\x7F]/', $decoded)) {
        return ['', ''];
    }
    // A password may contain colons; only the first colon separates the username.
    return explode(':', $decoded, 2);
}

