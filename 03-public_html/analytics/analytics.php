    stopRequest(401, 'Sign in to view analytics.');
}

function queryValue(string $key, int $maxBytes = 255): string
{
    $value = $_GET[$key] ?? '';
    if (!is_string($value) || strlen($value) > $maxBytes
        || !preg_match('//u', $value) || preg_match('/[\x00-\x1F\x7F]/u', $value)) {
        stopRequest(400, 'Invalid filter: ' . $key);
    }
    return $value;
}

function dateValue(string $key): ?DateTimeImmutable
{
    $value = queryValue($key, 10);
    if ($value === '') {
        return null;
    }
    $date = DateTimeImmutable::createFromFormat('!Y-m-d', $value, new DateTimeZone('UTC'));
    if (!$date || $date->format('Y-m-d') !== $value
        || $value < '1000-01-01' || $value > '9999-12-30') {
        stopRequest(400, 'Invalid date: ' . $key);
    }
    return $date;
}

function pageValue(string $key): int
{
    $value = queryValue($key, 7);
    if ($value === '') {
        return 1;
    }
    if (!preg_match('/\A[1-9][0-9]{0,6}\z/', $value) || (int) $value > 1000000) {
        stopRequest(400, 'Invalid page number.');
    }
    return (int) $value;
}

// Report queries use prepared statements. Only fixed SQL fragments are assembled.
function queryRows(mysqli $db, string $sql, string $types = '', array $values = []): array
{
    $statement = $db->prepare($sql);
    try {
        if ($types !== '') {
            $statement->bind_param($types, ...$values);
        }
        $statement->execute();
        $result = $statement->get_result();
        $rows = $result->fetch_all(MYSQLI_ASSOC);
        $result->free();
        return $rows;
    } finally {
        $statement->close();
    }
}

